const fs=require('node:fs'),assert=require('node:assert/strict'),vm=require('node:vm');
const source=fs.readFileSync('global-chart.js','utf8');
assert.deepEqual([...new Set([...source.matchAll(/'([a-z]+Chart)'/g)].map(x=>x[1]))],['bbChart','arChart','kdChart','opChart','lpChart','olChart','pbChart','jrChart']);
assert.ok(source.includes("JA.getActiveChart?.()"));
assert.ok(source.includes("JA.activateChart?.(+chart.dataset.chartIndex,{stay:true})"));
assert.ok(source.includes("data-global-chart-action=\"demo\""));
assert.ok(source.includes("data-global-chart-action=\"import\""));
assert.ok(source.includes("JA.openImportModal?.(action)"));
assert.ok(source.includes("data-remove-index"));
assert.ok(source.includes("Moon Nakshatra")===false,'The compact pill derives actual nakshatra instead of a static label.');
assert.ok(source.includes("nakInfo(moon.sign*30+moon.deg)"));
assert.ok(source.includes("celestial-gate"));
assert.ok(source.includes("id!=='pbChart'"),'Prompt builder must avoid recursive chart activation.');
const html=fs.readFileSync('index.html','utf8');
assert.ok(html.includes('global-chart.css'));
assert.ok(html.includes('global-chart.js'));
assert.ok(html.includes('JA.activateChart=(i,opts={})'));
assert.ok(html.includes('jyotish_active_chart_v1'));
assert.ok(html.includes('JA.openImportModal=openModal'));
assert.ok(html.includes('emitActiveChart();\n    try{JA.onChartsChange'));
assert.ok(html.includes("finally{queueMicrotask(emitActiveChart);}"),'active-chart publication must survive a legacy workspace error');
assert.ok(source.includes("window.addEventListener('atlas-active-chart-change'"));
assert.ok(html.includes('active=i;persistActive();draw();notifyActive()'),'switching must not rewrite all chart data before updating the interface');
assert.ok(html.includes('const legacyName=pill.querySelector(".cp-name");'),'legacy pill updater must tolerate global-pill markup');
assert.ok(html.includes('if(!legacyName) return;'),'a legacy callback must not abort active-chart updates');
assert.ok(source.includes("pill.dataset.globalChartPill='true'"));
assert.doesNotThrow(()=>new vm.Script(source));
console.log('Global active-chart source, switcher, gate and integration checks passed.');
